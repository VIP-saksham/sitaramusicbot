from pyrogram.types import InlineKeyboardButton
import config
from KeyaraMusic import app

def start_panel(_):
    buttons = [
        [
            InlineKeyboardButton(
                text=_["S_B_1"], url=f"https://t.me/{app.username}?startgroup=true"
            ),
            InlineKeyboardButton(text=_["S_B_2"], url=config.SUPPORT_GROUP),
        ],
        [
            InlineKeyboardButton(text=_["S_B_4"], callback_data="help_page_1"),
            InlineKeyboardButton(text=_["S_B_11"], callback_data="about_page"),
        ],
    ]
    return buttons

def private_panel(_):
    buttons = [
        [
            InlineKeyboardButton(
                text=_["S_B_3"],
                url=f"https://t.me/{app.username}?startgroup=true",
            )
        ],
        [
            InlineKeyboardButton(text=_["S_B_4"], callback_data="help_page_1"),
            InlineKeyboardButton(text=_["S_B_11"], callback_data="about_page"),
        ],
        [
            InlineKeyboardButton(text=_["S_B_12"], callback_data="owner_page"),
            InlineKeyboardButton(text=_['S_B_5'], url=f"https://t.me/{config.OWNER_USERNAME}"),
        ],
    ]
    return buttons

